# ==========================================
# 4. РОЗРАХУНОК ЙМОВІРНОСТЕЙ ДЛЯ РІЗНИХ ПОРОГІВ X (п. 1.3.4 - 1.3.8)
# ==========================================
results = []

# Сортуємо унікальні значення U_sh, щоб використовувати їх як пороги
thresholds = sorted(df["U_sh"].unique())
total_N = len(df)

for X_kl in thresholds:
    # Приймаємо рішення:
    # Якщо U_sh <= X_kl -> Вирішуємо K1
    # Якщо U_sh > X_kl  -> Вирішуємо K2

    # n(ріш К1 / К1) - True Positive (для К1)
    n_rK1_K1 = len(df[(df["U_sh"] <= X_kl) & (df["True_Class"] == "K1")])

    # n(ріш К2 / К2) - True Negative
    n_rK2_K2 = len(df[(df["U_sh"] > X_kl) & (df["True_Class"] == "K2")])

    # n(ріш К1 / К2) - Помилка: Вирішили К1, а насправді К2 (Пропуск браку)
    n_rK1_K2 = len(df[(df["U_sh"] <= X_kl) & (df["True_Class"] == "K2")])

    # n(ріш К2 / К1) - Помилка: Вирішили К2, а насправді К1 (Хибна тривога)
    n_rK2_K1 = len(df[(df["U_sh"] > X_kl) & (df["True_Class"] == "K1")])

    # Загальне число рішень
    n_rK1 = n_rK1_K1 + n_rK1_K2
    n_rK2 = n_rK2_K1 + n_rK2_K2

    # Ймовірності (п. 1.3.7)
    # P_pom (Ймовірність помилки) = (Помилкові рішення) / N
    P_pom = (n_rK1_K2 + n_rK2_K1) / total_N
    P_prav = 1 - P_pom

    results.append(
        {
            "X_kl": X_kl,
            "n(rK1/K1)": n_rK1_K1,
            "n(rK2/K2)": n_rK2_K2,
            "n(rK1/K2)": n_rK1_K2,  # Помилка пропуску
            "n(rK2/K1)": n_rK2_K1,  # Помилка хибної тривоги
            "n(rK1)": n_rK1,
            "n(rK2)": n_rK2,
            "P_pom": P_pom,
            "P_prav": P_prav,
        }
    )

results_df = pd.DataFrame(results)

# Відображення таблиці (перші та останні рядки, та область мінімуму помилки)
print("\nТаблиця результатів (фрагмент):")
print(results_df)

# ==========================================
# 5. ГРАФІКИ ЗАЛЕЖНОСТІ ЙМОВІРНОСТЕЙ (п. 1.3.9)
# ==========================================
plt.figure(figsize=(10, 6))
plt.plot(
    results_df["X_kl"],
    results_df["P_pom"],
    label="P помилки (сумарна)",
    color="red",
    linewidth=2,
)
plt.plot(
    results_df["X_kl"],
    results_df["P_prav"],
    label="P правильних рішень",
    color="green",
    linewidth=2,
)

# Знаходимо оптимальне значення (п. 1.3.10)
best_row = results_df.loc[results_df["P_prav"].idxmax()]
best_X = best_row["X_kl"]
max_P = best_row["P_prav"]

plt.axvline(
    x=best_X, color="black", linestyle="--", label=f"Оптимальний поріг ({best_X})"
)

plt.title("Залежність ймовірностей від порогу відсікання X_kl")
plt.xlabel("Значення порогу напруги шуму X_kl")
plt.ylabel("Ймовірність")
plt.legend()
plt.grid(True)
plt.show()

