import matplotlib.pyplot as plt

# --- ВСТАВТЕ ВАШІ ДАНІ З ТАБЛИЦІ 4.3 СЮДИ ---
N_values = [
    20000,
    40000,
    60000,
    80000,
    100000,
    120000,
    140000,
    160000,
    180000,
    200000,
    220000,
    240000,
]
# Приклад часу (у секундах), який ви отримали для MPI_Scatter:
scatter_times = [
    0.00018030,
    0.00014770,
    0.00018110,
    0.00032590,
    0.00029120,
    0.00043010,
    0.00044610,
    0.00045490,
    0.00038570,
    0.00052980,
    0.00071900,
    0.00055660,
]
# --------------------------------------------

plt.figure(figsize=(10, 6))
plt.plot(N_values, scatter_times, "m-o", label="Час виконання MPI_Scatter")

# Оформлення
plt.title("Залежність часу комунікацій від довжини масиву (P=4)", fontsize=14)
plt.xlabel("Довжина масиву (N)", fontsize=12)
plt.ylabel("Час (секунди)", fontsize=12)
plt.grid(True, linestyle="--", alpha=0.7)
plt.ticklabel_format(
    style="sci", axis="y", scilimits=(0, 0)
)  # Для зручного відображення малих чисел
plt.legend()
plt.show()

print(
    "Графік побудовано. Якщо лінія майже пряма — це означає лінійну залежність часу від об'єму даних."
)
